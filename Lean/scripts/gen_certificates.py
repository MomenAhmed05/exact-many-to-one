# -*- coding: utf-8 -*-
"""Write ExactManyToOne/Certificates.lean from the deposited certificates.

The interval-arithmetic certificates of Sections 9.11 and 10.4-10.6 are computed
in Python. Lean does not recompute them. What it does check, exactly, is every
step that turns a deposited number into a headline claim:

* Table 15: each cell's gap c_U - c_L against the declared tolerance, in the
  direction its "certified" label claims, so a mislabelled cell fails to build;
* Table 17: each one-candidate bound, plus the 4e-9 tail mass, under the ceiling;
* Table 19: K (or 2K) times each one-candidate bound under the ceiling, and the
  headline error-rate theorem for that design obtained from `union_step` or
  `two_sided_union`;
* Table 20: K times each projected per-candidate bound under the ceiling.

Every float is converted to the exact rational it denotes in binary, so the
comparison is the one the deposit actually made, with no decimal rounding.

Run from the Lean directory:  python scripts/gen_certificates.py
"""
import json
import os
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEP03 = os.path.join(ROOT, '03-certified-supremum', 'deposits')
DEP04 = os.path.join(ROOT, '04-efficient-rule', 'deposits')
OUT = os.path.join(os.path.dirname(HERE), 'ExactManyToOne', 'Certificates.lean')


def q(x):
    """The exact rational value of a float, as a Lean term."""
    f = Fraction(x)
    return '(%d / %d : ℚ)' % (f.numerator, f.denominator) if f.denominator != 1 \
        else '(%d : ℚ)' % f.numerator


def r(x):
    """The same, as a real."""
    f = Fraction(x)
    return '((%d : ℝ) / %d)' % (f.numerator, f.denominator)


def ident(s):
    return ''.join(ch if ch.isalnum() else '_' for ch in s)


def load(d, name):
    with open(os.path.join(d, name), encoding='utf-8') as fh:
        return json.load(fh)


def main():
    out = []
    w = out.append
    w('/-')
    w('Copyright (c) 2026 Momen Ahmed. All rights reserved.')
    w('Released under MIT license as described in the file LICENSE.')
    w('Authors: Momen Ahmed')
    w('-/')
    w('import ExactManyToOne.Calibrated')
    w('')
    w('/-!')
    w('# The deposited certificates, checked exactly')
    w('')
    w('Generated by `scripts/gen_certificates.py` from the JSON deposits. Do not edit by')
    w('hand. Each number is the exact binary value of the deposited float.')
    w('')
    w('The enclosures themselves are computed in Python with interval arithmetic in')
    w('directed rounding and are not recomputed here. Their outputs enter as the')
    w('hypotheses named `hcert`. What Lean checks is that each output supports the claim')
    w('the paper makes from it, and that each pass/fail label is the right one.')
    w('-/')
    w('')
    w('-- exact binary rationals do not fit in 100 columns')
    w('set_option linter.style.longLine false')
    w('')
    w('open MeasureTheory')
    w('open scoped ENNReal')
    w('')
    w('namespace ExactManyToOne.Certificates')
    w('')
    w('/-- Moving a real certificate inequality into the extended nonnegative reals. -/')
    w('lemma ennreal_bound {m : ℕ} {b a : ℝ} (h : (m : ℝ) * b ≤ a) :')
    w('    (m : ℝ≥0∞) * ENNReal.ofReal b ≤ ENNReal.ofReal a := by')
    w('  rw [← ENNReal.ofReal_natCast, ← ENNReal.ofReal_mul (by positivity)]')
    w('  exact ENNReal.ofReal_le_ofReal h')
    w('')

    # ---- Table 15: branch and bound --------------------------------------
    bnb = load(DEP03, 'bnb.json')
    tol = bnb['tol']
    n_cert = 0
    w('/-! ## Table 15: the certified supremum, cell by cell')
    w('')
    w('A cell labelled certified must have `c_U - c_L ≤ tol`; a cell labelled not')
    w('certified must have `tol < c_U - c_L`. With `certificate_brackets`, a certified')
    w('cell pins the supremum of the constant over its region to within `tol`. -/')
    w('')
    for k, cell in enumerate(bnb['cells']):
        cu, cl = cell['c_U'], cell['c_L']
        assert Fraction(cell['gap']) == Fraction(cu) - Fraction(cl), cell
        name = 'table15_cell%02d' % (k + 1)
        if cell['certified_at_tol']:
            n_cert += 1
            assert Fraction(cu) - Fraction(cl) <= Fraction(tol)
            w('theorem %s_certified : %s - %s ≤ %s := by norm_num' % (name, q(cu), q(cl), q(tol)))
        else:
            assert Fraction(cu) - Fraction(cl) > Fraction(tol)
            w('theorem %s_not_certified : %s < %s - %s := by norm_num' % (name, q(tol), q(cu), q(cl)))
    assert n_cert == bnb['n_certified_at_tol']
    w('')
    w('/-- %d of the %d cells certify at the declared tolerance. -/' % (n_cert, bnb['n_cells']))
    w('theorem table15_count : (%d : ℕ) = %d := rfl' % (n_cert, bnb['n_certified_at_tol']))
    w('')

    # ---- Table 17: one candidate ------------------------------------------
    k1 = load(DEP04, 'wb_certified_rule.json')
    abar = k1['abar']
    tail = k1['tail_mass_correction']['omitted_probability_mass']
    w('/-! ## Table 17: the one-candidate certificates')
    w('')
    w('Each certified supremum of the unconditional error rate is under the ceiling, and')
    w('it stays under the ceiling after adding the tail mass `4 p_min` of equation (41),')
    w('so the conclusion holds whether or not the deposited bound already includes it. -/')
    w('')
    for d in k1['designs']:
        ub = d['sup_upper_bound']
        assert d['certified'] == 1
        assert Fraction(ub) + Fraction(tail) <= Fraction(abar)
        w('theorem table17_%s : %s + %s ≤ %s := by norm_num' % (ident(d['design']), q(ub), q(tail), q(abar)))
    w('')

    # ---- Table 19: the per-candidate rule at any K ---------------------------
    ak = load(DEP04, 'certify_anyk.json')
    abar = ak['abar']
    w('/-! ## Table 19: the per-candidate rule at two, three and five candidates')
    w('')
    w('For each design: `m · K · b ≤ ᾱ` with `m = 2` two-sided, checked exactly, and the')
    w('familywise guarantee for that design derived from the union step. The hypothesis')
    w('`hcert` is the deposited one-candidate enclosure. -/')
    w('')
    for d in ak['designs']:
        K = d['K']
        m = 2 if d['two_sided'] else 1
        b = d['one_candidate_bound']
        assert d['certified'] == 1
        assert m * K * Fraction(b) <= Fraction(abar)
        assert Fraction(d['exact_sup_over_patterns']) <= m * K * Fraction(b)
        side = 'two_sided' if m == 2 else 'one_sided'
        base = 'table19_%s_%s' % (ident(d['design']), side)
        w('theorem %s_arith : (%d : ℚ) * %s ≤ %s := by norm_num' % (base, m * K, q(b), q(abar)))
        w('')
        w('/-- The deployed rule\'s own exact error rate sits under the certified total. -/')
        w('theorem %s_dominates : %s ≤ (%d : ℚ) * %s := by norm_num'
          % (base, q(d['exact_sup_over_patterns']), m * K, q(b)))
        w('')
        w('/-- **Design %s, %s: familywise error rate at most %s.** -/' % (d['design'], side.replace('_', '-'), abar))
        w('theorem %s {Ω Λ : Type*} [MeasurableSpace Ω] {P : Measure Ω}' % base)
        if m == 1:
            w('    (Rej : Fin %d → Set Ω) (FWER1 : Λ → ℝ≥0∞) (lam : Fin %d → Λ) (D : Set Λ)' % (K, K))
            w('    (hD : ∀ i, lam i ∈ D) (hmarg : ∀ i, P (Rej i) = FWER1 (lam i))')
            w('    (hcert : ∀ l ∈ D, FWER1 l ≤ ENNReal.ofReal %s) :' % r(b))
            w('    P (⋃ i, Rej i) ≤ ENNReal.ofReal %s :=' % r(abar))
            w('  (union_step Rej FWER1 lam D hD hmarg _ hcert).trans')
            w('    (ennreal_bound (m := %d) (by norm_num))' % K)
        else:
            w('    (Rej2 Rej1 : Fin %d → Set Ω) (FWER1 : Λ → ℝ≥0∞) (lam : Fin %d → Λ) (D : Set Λ)' % (K, K))
            w('    (hD : ∀ i, lam i ∈ D) (htwice : ∀ i, P (Rej2 i) = 2 * P (Rej1 i))')
            w('    (hmarg : ∀ i, P (Rej1 i) = FWER1 (lam i))')
            w('    (hcert : ∀ l ∈ D, FWER1 l ≤ ENNReal.ofReal %s) :' % r(b))
            w('    P (⋃ i, Rej2 i) ≤ ENNReal.ofReal %s := by' % r(abar))
            w('  refine (two_sided_union Rej2 Rej1 FWER1 lam D hD htwice hmarg _ hcert).trans ?_')
            w('  have h := ennreal_bound (m := %d) (b := %s) (a := %s) (by norm_num)'
              % (2 * K, r(b), r(abar)))
            w('  refine le_trans (le_of_eq ?_) h')
            w('  push_cast')
            w('  ring')
        w('')

    # ---- Table 20: the joint rule ---------------------------------------------
    jt = load(DEP04, 'certify_joint.json')
    abar = jt['abar']
    w('/-! ## Table 20: the joint rule by projection')
    w('')
    w('`K` times the projected per-candidate bound is under the ceiling, and the deployed')
    w('joint rule\'s own error rate is under that total. -/')
    w('')
    for d in jt['designs']:
        K = d['K']
        b = d['per_candidate_bound']
        assert d['certified'] == 1
        assert K * Fraction(b) <= Fraction(abar)
        assert Fraction(d['exact_sup_over_patterns']) <= K * Fraction(b)
        base = 'table20_%s' % ident(d['design'])
        w('theorem %s_arith : (%d : ℚ) * %s ≤ %s := by norm_num' % (base, K, q(b), q(abar)))
        w('theorem %s_dominates : %s ≤ (%d : ℚ) * %s := by norm_num'
          % (base, q(d['exact_sup_over_patterns']), K, q(b)))
    w('')
    w('end ExactManyToOne.Certificates')
    w('')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out))
    print('wrote %s' % OUT)
    print('  table 15: %d cells (%d certified)' % (len(bnb['cells']), n_cert))
    print('  table 17: %d designs' % len(k1['designs']))
    print('  table 19: %d designs' % len(ak['designs']))
    print('  table 20: %d designs' % len(jt['designs']))


if __name__ == '__main__':
    main()
