"""Consolidated soundness audit for the S-kappa / COMP-THM programme.

Builds `W4lean/AxAll.lean`, which is GENERATED from the proof-file sources so that a public
theorem cannot be added to a proof file without appearing in the audit, then checks that every
one of them depends on exactly the three standard axioms and nothing else.  Any `sorryAx`, or
any other axiom, is a failure of the whole programme's Lean layer.

This is the artifact an independent auditor should be pointed at: it is regenerated from source
rather than hand-listed, and its verdict is computed rather than asserted.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
W = ROOT / "lean/W4lean"

PROOF_FILES = [
    "Unit2BFormalR1Proofs.lean", "Unit2BFormalR1R2.lean", "Unit2BKappaProofsR1.lean", "Unit2BKappaProofsR2.lean",
    "Unit2BKappaProofsR3.lean", "Unit2BKappaProofsR4.lean", "Unit2BKappaProofsR5.lean",
    "Unit2BKappaProofsR6.lean", "Unit2BKappaProofsR7.lean", "Unit2BKappaProofsR8.lean",
    "Unit2BKappaProofsR9.lean", "Unit2BKappaProofsR10.lean",
    "Unit2BSizeR11.lean", "Unit2BSizeConsR11.lean", "Unit2BSizeConsAsmR11.lean",
    "ChiSquaredSpikeR1.lean",
    "ProductMarginalR1.lean", "OrthonormalCoordsR1.lean", "ParsevalR1.lean",
]
STANDARD = {"propext", "Classical.choice", "Quot.sound"}

imports, opens, body = [], ["open MeasureTheory ProbabilityTheory Real Set"], []
for f in PROOF_FILES:
    p = W / f
    if not p.exists():
        continue
    imports.append(f"import W4lean.{f[:-5]}")
    txt = p.read_text(encoding="utf-8")
    opens += [f"open {x}" for x in re.findall(r"^namespace\s+([A-Za-z_][A-Za-z0-9_.']*)", txt, re.M)]
    names = re.findall(r"^theorem\s+([A-Za-z_][A-Za-z0-9_']*)", txt, re.M)
    if names:
        body.append(f"-- {f}")
        body += [f"#print axioms {n}" for n in names]
        body.append("")

ax = W / "AxAll.lean"
# Coverage: BOTH `theorem` and `lemma`, and BOTH public and private / indented forms.
# An independent review flagged that anchoring on `^theorem` would miss `private theorem`
# and indented declarations.  Measured on these nine files that particular hole is empty
# (strict and loose patterns both find 47), but the review also noted the comparator could
# pass with a declaration missed on BOTH sides, so the pattern below is deliberately loose
# and the completeness check is on counts as well as names.
DECL = re.compile(r"^\s*(?:@\[[^\]]*\]\s*)?((?:private\s+|protected\s+|noncomputable\s+)*)"
                 r"(theorem|lemma)\s+([A-Za-z_][^\s:]*)", re.M)
NS_OPEN = re.compile(r"^\s*namespace\s+([A-Za-z_][\w'.]*)")
NS_CLOSE = re.compile(r"^\s*end\s+([A-Za-z_][\w'.]*)")
names_all, private_all = [], []
# NAMESPACE DEFECT, fixed 2026-09-30.  This loop collected the SHORT name only, so
# `AxAll.lean` said `#print axioms nu_eq` while the kernel reports
# `Unit2B.FormalR1.Proofs.nu_eq`.  Two consequences followed, both bad:
#   (a) the completeness test could only ever compare short against short, so a declaration
#       shadowed by a same-named one in a different namespace could be counted as reported
#       when it was not -- the hole an earlier review identified;
#   (b) the ambiguity guard added afterwards COULD NOT FIRE, because every declared name was
#       already short, so `_by_short[d]` was always a set of one.  `AMBIGUOUS=0` was
#       guaranteed by construction, which is a guard that looks armed and is not.
# The fix is to carry each file's namespace stack and emit FULLY QUALIFIED names, so that
# declared and reported are the same string on both sides and the guard means something.
for f in PROOF_FILES:
    p = W / f
    if not p.exists():
        continue
    stack = []
    for ln in p.read_text(encoding="utf-8").splitlines():
        mo = NS_OPEN.match(ln)
        if mo:
            stack.append(mo.group(1))
            continue
        mc = NS_CLOSE.match(ln)
        if mc and stack and stack[-1] == mc.group(1):
            stack.pop()
            continue
        md = DECL.match(ln)
        if md:
            mods, _kind, short = md.groups()
            full = ".".join(stack) + "." + short if stack else short
            (private_all if "private" in mods else names_all).append((f, full))

body = ["-- generated coverage"] + [
    f"#print axioms {n}   -- {f}" for f, n in names_all]
ax.write_text("\n".join([
    "-- GENERATED by formal01_ax_all.py -- do not edit by hand.",
    "-- One #print axioms per theorem AND lemma, public and private, across every proof file.",
] + sorted(set(imports)) + sorted(set(opens)) + [""] + body) + "\n", encoding="utf-8")

# Build the generated file from the Lean project folder and read the FULL compiler output.
# Reading only the tail of it is what once made a run report 21 of 47 declarations and call
# it a FAIL.
proc = subprocess.run(["lake", "build", "W4lean.AxAll"],
                      cwd=ROOT / "lean", capture_output=True, text=True, encoding="utf-8")
blob = proc.stdout + proc.stderr
# NOTE: the name character class MUST include the trailing prime.  A first version used
# [A-Za-z_0-9.] and silently dropped it, so the two theorems whose names end in `'` were
# read as "declared but not reported by the kernel" and the audit reported FAIL.  Both were
# in fact axiom-clean.  That is the third time in this programme a defect in my own checking
# instrument has looked like a substantive finding, so the class is now spelled out here.
found = re.findall(r"'([A-Za-z_0-9.']+)' depends on axioms: \[([^\]]*)\]", blob)
declared_names = [n for _, n in names_all]
reported_names = {n.split(".")[-1] for n, _ in found}

# REPLAY, 2026-09-30.  `lake build` REPLAYS an upstream module's stored info messages
# alongside the ones the requested target emits.  When Unit2BKappaProofsR5 was first
# audited, the three public declarations of that module were printed TWICE -- once from
# `Replayed W4lean.Unit2BKappaProofsR5` and once from `AxAll.lean` -- so the raw line count
# was 54 against 51 declared names.
#
# The completeness test was `not unreported and len(found) == len(declared_names)`, and that
# COUNT EQUALITY is the wrong invariant: it fails on a replayed duplicate exactly as it would
# pass on a duplicated line, and it says nothing about whether a name was actually reported.
# It produced a FAIL with declared=51, reported-distinct=51, unreported=0, sorryAx=0 and no
# violations -- i.e. a total false negative, in the direction opposite to the vacuous-PASS
# guard added earlier for the same reason.
#
# The correct test is the SET test: every declared name appears among the reported names.  The
# duplicates are NOT silently absorbed: they are reported below by name, so the replay stays
# visible and this fix can be audited rather than taken on trust.
_seen = {}
for _n, _ in found:
    _seen[_n] = _seen.get(_n, 0) + 1
replayed = sorted(k for k, v in _seen.items() if v > 1)

out = [f"CLAIM AXA-BUILD-EXIT: lake build W4lean.AxAll exit status = {proc.returncode}",
       f"CLAIM AXA-ERRORS: build errors = {len(re.findall(r'^error', blob, re.M))}",
       f"CLAIM AXA-DECLARED: PUBLIC declarations (theorem AND lemma) audited = "
       f"{len(declared_names)}",
       f"CLAIM AXA-REPORTED: axiom lines returned by the kernel = {len(found)}",
       f"CLAIM AXA-REPORTED-DISTINCT: DISTINCT declarations reported by the kernel = "
       f"{len(reported_names)}",
       f"CLAIM AXA-REPLAYED: names printed more than once by `lake`, because `lake build` "
       f"replays an upstream module's stored info messages alongside the target's = "
       f"{len(replayed)}"
       + ("" if not replayed else f" ({', '.join(n.split('.')[-1] for n in replayed)})")]

bad = []
for name, axs in found:
    got = {a.strip() for a in axs.split(",") if a.strip()}
    if not got <= STANDARD:
        bad.append(f"{name}={sorted(got - STANDARD)}")

out.append(f"CLAIM AXA-CLEAN: theorems on exactly the three standard axioms = "
           f"{len(found) - len(bad)}")
out.append("CLAIM AXA-VIOLATIONS: theorems depending on anything beyond the three standard axioms = "
           + ("none" if not bad else "; ".join(bad)))
out.append(f"CLAIM AXA-SORRYAX: theorems depending on sorryAx = "
           f"{sum('sorryAx' in a for _, a in found)}")
unreported = [d for d in declared_names if d not in reported_names]
# NAME-MATCHING, and the second correction to it, 2026-09-30 after the R10 port.
#
# ATTEMPT 1, which was WRONG: compare FULL names on both sides.  The generator writes SHORT
# names into AxAll.lean, while the kernel prints FULLY QUALIFIED names, so full-vs-full never
# matched anything and the audit reported 155 of 163 unreported.  The failure was loud --
# AXA-VERDICT: FAIL -- which is the only reason it was caught.  Recorded because a plausible
# "obvious" fix made the instrument strictly worse.
#
# THE CORRECT TEST IS AMBIGUITY-AWARE.  A declared name counts as reported if its full name
# appears, OR if it is a bare name and it is the UNIQUE declared declaration carrying that
# short name and the kernel reported that short name.  A short name claimed by two
# declarations in different namespaces is ambiguous and must NOT be accepted on the short
# match alone -- that is precisely the hole the short-name test had, since the R10 port
# introduced declarations shadowing older same-named ones.
reported_full = {n for n, _ in found}
reported_short = {n.split(".")[-1] for n, _ in found}
_by_short = {}
for d in declared_names:
    _by_short.setdefault(d.split(".")[-1], set()).add(d)
ambiguous = {s for s, ds in _by_short.items() if len(ds) > 1}


def _is_reported(d):
    if d in reported_full:
        return True
    s = d.split(".")[-1]
    if s in ambiguous:
        return False           # cannot decide on a bare name; fail loudly
    return s in reported_short and "." not in d


unreported = [d for d in declared_names if not _is_reported(d)]
shadowed = sorted({d for d in declared_names if not _is_reported(d)})
# `private` declarations CANNOT be reached by `#print axioms` under their short name, so
# they legitimately produce no kernel line.  They are not a coverage hole: a private lemma
# is covered TRANSITIVELY, because any public theorem that depends on it inherits its
# axioms, so a sorryAx anywhere on a path to a public theorem would appear in that
# theorem's list.  A private lemma reachable from no public theorem is dead code and
# cannot affect any claim.  This is why `AXA-PRIVATE` is reported separately rather
# than counted as a failure.
out.append(f"CLAIM AXA-PRIVATE: private declarations present (covered transitively, not "
           f"audited by name) = {len(private_all)}")
out.append("CLAIM AXA-PRIVATE-NAMES: " + (", ".join(n for _, n in private_all) or "none"))
out.append("CLAIM AXA-COMPLETE: every PUBLIC declaration was reported by the kernel = "
           + str(not unreported and bool(declared_names))
           + ("" if not unreported else f" (unreported: {', '.join(unreported)})"))
out.append(f"CLAIM AXA-AMBIGUOUS: short names claimed by MORE THAN ONE declared declaration, "
           f"so a bare-name match cannot decide them = {len(ambiguous)}"
           + ("" if not ambiguous else f" ({', '.join(sorted(ambiguous))})"))
out.append(f"CLAIM AXA-SHADOWED: declared names not matched by the ambiguity-aware test = "
           f"{len(shadowed)}"
           + ("" if not shadowed else f" ({', '.join(shadowed)})"))
out.append("CLAIM AXA-VACUOUS-GUARD: an audit declaring ZERO declarations is a FAILURE not a "
           "PASS, since completeness would compare two empty sets = "
           + ("GUARD TRIGGERED (declared=0)" if not declared_names
              else f"declared={len(declared_names)}, guard not triggered"))
out.append("CLAIM AXA-SCOPE: this audit certifies the LEAN LAYER ONLY, that the named "
           "declarations depend on nothing beyond propext, Classical.choice and Quot.sound.")
out.append("CLAIM AXA-SCOPE-CONT: it does NOT certify the Arb numerical enclosure, the paper "
           "Helmert proof, or that the certified bound is the correct bound. A narrow PASS "
           "here is not programme completion.")
out.append("CLAIM AXA-VERDICT: Lean-layer soundness audit = "
           # The SET test, not the count test.  See the REPLAY note above: `lake build`
           # replays an upstream module's stored info messages, so the raw line count can
           # exceed the number of distinct declarations with nothing wrong anywhere.  The
           # count test produced a FAIL here with 0 unreported, 0 sorryAx and 0 violations.
           + ("PASS" if (not bad and proc.returncode == 0 and not unreported
                         and bool(declared_names))
              else "FAIL"))

(ROOT / "deposits" / "ax_all_claims.txt").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out))
